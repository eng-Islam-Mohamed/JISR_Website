const $ = (selector) => document.querySelector(selector);
const $$ = (selector) => [...document.querySelectorAll(selector)];
const root = document.documentElement;
const systemMotion = matchMedia("(prefers-reduced-motion: reduce)");
let language = "ar";
let phrase = "water";
let screen = "gallery";
let speechTimer;
let activeUtterance;
let speechGeneration = 0;
const store = {
  get(key) {
    try {
      return localStorage.getItem(key);
    } catch {
      return null;
    }
  },
  set(key, value) {
    try {
      localStorage.setItem(key, value);
    } catch {
      /* Preferences are optional. */
    }
  },
};
const t = (key) => translations[language][key];

function endSpeech(statusKey = "speechHint", error = false) {
  clearTimeout(speechTimer);
  $("#speak").classList.remove("speaking");
  $("#speak").querySelector("span").textContent = t("listen");
  $("#speech-status").textContent = t(statusKey);
  $("#speech-status").dataset.error = String(error);
  activeUtterance = null;
}
function cancelSpeech() {
  speechGeneration++;
  if ("speechSynthesis" in window) window.speechSynthesis.cancel();
  endSpeech();
}
function setLanguage(next) {
  if (!translations[next]) return;
  cancelSpeech();
  language = next;
  root.lang = next;
  root.dir = next === "ar" ? "rtl" : "ltr";
  document.title = t("title");
  $$("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  $$("[data-i18n-aria]").forEach((el) =>
    el.setAttribute("aria-label", t(el.dataset.i18nAria)),
  );
  $$("[data-i18n-alt]").forEach((el) => {
    el.alt = t(el.dataset.i18nAlt);
  });
  $("#language-current").textContent = next.toUpperCase();
  $$(".language-menu button").forEach((b) =>
    b.setAttribute("aria-pressed", String(b.dataset.lang === next)),
  );
  $("#hero-screen").src = `assets/screens/home-${next}.png`;
  $("#demo-phrase").textContent = t("phrases")[phrase];
  $("#speech-status").textContent = t("speechHint");
  $(".handwritten").textContent =
    next === "ar"
      ? "صورة، كلمة، وصلة."
      : next === "fr"
        ? "Une image. Un lien."
        : "A picture. A connection.";
  $("#showcase-screen").src = `assets/screens/${screen}-${language}.png`;
  $("#scene-note").textContent = t(
    screen === "gallery"
      ? "categoriesCaption"
      : screen === "detail"
        ? "voiceCaption"
        : "calmCaption",
  );
  $("#download-feedback").textContent = "";
  document.querySelector("meta[name=description]").content =
    t("heroDescription");
  closeLanguages();
  updateMotionLabel();
  store.set("jisr-site-language", next);
}
function closeLanguages(restoreFocus = false) {
  $("#languages").hidden = true;
  $(".language-toggle").setAttribute("aria-expanded", "false");
  if (restoreFocus) $(".language-toggle").focus();
}
$(".language-toggle").addEventListener("click", () => {
  const open = $("#languages").hidden;
  $("#languages").hidden = !open;
  $(".language-toggle").setAttribute("aria-expanded", String(open));
  if (open) $("#languages button[aria-pressed=true]").focus();
});
$$("[data-lang]").forEach((button) =>
  button.addEventListener("click", () => {
    setLanguage(button.dataset.lang);
    $(".language-toggle").focus();
  }),
);
document.addEventListener("click", (event) => {
  if (!event.target.closest(".language-picker")) closeLanguages();
});
$(".language-picker").addEventListener("keydown", (event) => {
  if (event.key === "Escape") closeLanguages(true);
  if (
    !$("#languages").hidden &&
    ["ArrowDown", "ArrowUp", "Home", "End"].includes(event.key)
  ) {
    event.preventDefault();
    const buttons = $$("#languages button");
    const index = buttons.indexOf(document.activeElement);
    const next =
      event.key === "Home"
        ? 0
        : event.key === "End"
          ? buttons.length - 1
          : (index + (event.key === "ArrowDown" ? 1 : -1) + buttons.length) %
            buttons.length;
    buttons[next].focus();
  }
});
$$("[data-phrase]").forEach((button) =>
  button.addEventListener("click", () => {
    cancelSpeech();
    phrase = button.dataset.phrase;
    $$("[data-phrase]").forEach((b) => {
      b.setAttribute("aria-pressed", String(b === button));
      b.classList.toggle("selected", b === button);
    });
    $("#demo-phrase").textContent = t("phrases")[phrase];
  }),
);
$("#speak").addEventListener("click", () => {
  if (activeUtterance) {
    cancelSpeech();
    return;
  }
  if (!("speechSynthesis" in window)) {
    endSpeech("speechError", true);
    return;
  }
  window.speechSynthesis.cancel();
  const voices = speechSynthesis.getVoices();
  const voice = voices.find((v) => v.lang.toLowerCase().startsWith(language));
  if (voices.length && !voice) {
    endSpeech("voiceMissing", true);
    return;
  }
  const utterance = new SpeechSynthesisUtterance(t("phrases")[phrase]);
  const generation = ++speechGeneration;
  utterance.lang = { ar: "ar-DZ", fr: "fr-FR", en: "en-GB" }[language];
  if (voice) utterance.voice = voice;
  utterance.rate = 0.85;
  activeUtterance = utterance;
  $("#speak").classList.add("speaking");
  $("#speak span").textContent = t("stop");
  $("#speech-status").textContent = t("speaking");
  $("#speech-status").dataset.error = "false";
  utterance.onend = () => {
    if (generation === speechGeneration) endSpeech("speechDone");
  };
  utterance.onerror = () => {
    if (generation === speechGeneration) endSpeech("speechError", true);
  };
  speechTimer = setTimeout(() => {
    if (generation === speechGeneration) {
      cancelSpeech();
      endSpeech("speechError", true);
    }
  }, 15000);
  try {
    speechSynthesis.speak(utterance);
  } catch {
    endSpeech("speechError", true);
  }
});
